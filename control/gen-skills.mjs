// Bundles ../skills/*.md (the agent instructions) into src/skills.gen.ts for
// the MCP server's guide(topic). Wrangler runs it before dev and deploy.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, "../skills");
const skills = {};
if (fs.existsSync(dir))
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".md")).sort())
    skills[f.replace(/\.md$/, "")] = fs.readFileSync(path.join(dir, f), "utf8");
if (!skills.index)
  skills.index = fs.readFileSync(path.join(here, "../templates/project/AGENTS.md"), "utf8");
const out = path.join(here, "src/skills.gen.ts");
const text = `// generated by gen-skills.mjs from skills/*.md; do not edit\nexport const SKILLS: Record<string, string> = ${JSON.stringify(skills, null, 1)};\n`;
// only on change: wrangler dev watches src/ and would rebuild forever
if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== text) fs.writeFileSync(out, text);
